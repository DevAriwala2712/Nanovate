"""Find the demo presets for the video by a deterministic seed search on the VALIDATION split only. Synthetic data.

Each scenario fixes (family, defect kind, dose 50, LER 1.0 nm, grain 0.15, seeded shift, layout 0, die 0,
split "val") and scans seeds 0, 1, 2, ... in order; the FIRST seed whose app response (the default v3 pipeline,
through the same /api/v1/verify route the UI calls) meets the scenario's condition is kept. Never the test split.
These are **selected illustrative examples**, chosen because they show a behaviour; they say nothing about typical
performance (see the README results tables for that).

Writes frontend/data/demo_presets.json (served to the UI's Live > Presets dropdown; tests/app/test_app_presets.py
checks every preset still produces its documented outcome).
Usage: python scripts/find_demo_presets.py [--max-seed 400] [--version v3]
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

OUT = Path("frontend/data/demo_presets.json")
SCHEMA_VERSION = 1
LABEL = "Selected illustrative examples, validation split (synthetic). Not typical performance."
BASE = {"dose": 50.0, "ler_sigma": 1.0, "grain": 0.15, "shift": None, "warp": 0.0, "split": "val", "layout_id": 0, "die": 0}


def _killer(v: str) -> bool:
    return v.startswith("KILLER")


# id, title, family, kinds tried per seed (in order), condition on the /verify response, documented outcome text
SCENARIOS = [
    ("via_bridge_cnn_miss", "Via layout, bridge: Nanovate KILLER, CNN misses", "via", ("bridge",),
     lambda r: _killer(r["verifier"]["verdict"]) and not r["cnn"]["flagged"] and r["truth"]["label"] == "KILLER"),
    ("via_ler_nuisance", "Via layout, roughness only (LER): Nanovate NUISANCE", "via", ("nuisance",),
     lambda r: r["verifier"]["verdict"] == "NUISANCE" and r["truth"]["label"] == "NUISANCE"),
    ("manhattan_notch_near_miss", "Notch (wire pinched, not cut): Nanovate NEAR_MISS", "manhattan", ("notch",),
     lambda r: r["verifier"]["verdict"] == "NEAR_MISS"),
    ("manhattan_honest_loss", "Manhattan (CNN's training layout): CNN correct, Nanovate wrong (honest loss)", "manhattan",
     ("bridge", "open", "particle", "nuisance"),
     lambda r: r["agreement"]["cnn"] == "agrees" and r["agreement"]["verifier"] == "disagrees"),
]


def outcome(r: dict) -> dict:
    return {"verifier_verdict": r["verifier"]["verdict"], "cnn_flagged": bool(r["cnn"]["flagged"]), "truth_label": r["truth"]["label"],
            "verifier_agrees": r["agreement"]["verifier"] == "agrees", "cnn_agrees": r["agreement"]["cnn"] == "agrees"}


def search(client, max_seed: int) -> list[dict]:
    out = []
    for sid, title, family, kinds, cond in SCENARIOS:
        hit = None
        for seed in range(max_seed + 1):
            for kind in kinds:
                params = {**BASE, "family": family, "kind": kind, "seed": seed}
                r = client.post("/api/v1/verify", json={"simulate": params}).json()
                if "error" in r:
                    continue
                if cond(r):
                    hit = (params, r, seed)
                    break
            if hit:
                break
        if hit is None:
            raise SystemExit(f"no seed in 0..{max_seed} meets scenario {sid!r}; raise --max-seed")
        params, r, seed = hit
        out.append({"id": sid, "title": title, "params": params, "expected": outcome(r),
                    "seeds_scanned": seed + 1, "pipeline_version": r["pipeline_version"]})
        print(f"{sid}: seed {seed} kind {params['kind']} -> verifier {r['verifier']['verdict']}, CNN {'KILLER' if r['cnn']['flagged'] else 'not killer'}, "
              f"truth {r['truth']['label']}", flush=True)
    return out


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--max-seed", type=int, default=400)
    ap.add_argument("--version", default="v3", choices=("v2", "v3"))
    a = ap.parse_args()
    from fastapi.testclient import TestClient

    from nanovate.app.api import create_app
    from nanovate.app.engine import Engine

    client = TestClient(create_app(Engine(version=a.version), frontend=None))
    presets = search(client, a.max_seed)
    OUT.write_text(json.dumps({"schema_version": SCHEMA_VERSION, "pipeline_version": a.version, "label": LABEL,
                               "selection": "first seed (scanning 0, 1, 2, ...) on the val split whose response meets the scenario; "
                                            "generated by scripts/find_demo_presets.py", "base_params": BASE,
                               "data": "synthetic", "presets": presets}, indent=1) + "\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
