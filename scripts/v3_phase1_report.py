"""Render the generated tables of docs/V3_PHASE1_DIAGNOSIS.md from results/v3/phase1/*.csv (never typed by hand).

Rewrites the text between <!-- PHASE1:START --> and <!-- PHASE1:END -->. Synthetic data, Manhattan val only.
Usage: python scripts/v3_phase1_report.py
"""
from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from experiments.report import _md, update_block  # noqa: E402

ROOT = Path("results/v3/phase1")
DOC = Path("docs/V3_PHASE1_DIAGNOSIS.md")
START, END = "<!-- PHASE1:START -->", "<!-- PHASE1:END -->"


def _ci(m, lo, hi, n, pct=True) -> str:
    if pd.isna(m):
        return f"n/a (n={int(n)})"
    return f"{100 * m:.0f}% [{100 * lo:.0f}, {100 * hi:.0f}] (n={int(n)})" if pct else f"{m:.2f} [{lo:.2f}, {hi:.2f}] (n={int(n)})"


def _arm(r) -> str:
    return f"{r.s}x ({r.pixel_nm:g} nm/px)" + ("" if r.blur_scale == 1.0 else f", optics x{r.blur_scale:g} (supplementary)")


def render() -> str:
    sm, orc = pd.read_csv(ROOT / "sampling.csv"), pd.read_csv(ROOT / "oracle_tau.csv")
    sz, miss = pd.read_csv(ROOT / "size_recall.csv"), pd.read_csv(ROOT / "miss_log.csv")
    parts = ["_Generated by `scripts/v3_phase1_report.py` from `results/v3/phase1/`. **Synthetic data, Manhattan val only, noise-free "
             "expected images at dose 50 e-/px, frozen v2 verifier.** 95% percentile-bootstrap CIs, n beside every number._"]

    rows = [[_arm(r), _ci(r.f1, r.ci_lo, r.ci_hi, r.n, False), _ci(r.recall_bridge, r.recall_bridge_lo, r.recall_bridge_hi, r.n_bridge),
             _ci(r.recall_open, r.recall_open_lo, r.recall_open_hi, r.n_open), _ci(r.recall_particle, r.recall_particle_lo, r.recall_particle_hi, r.n_particle),
             _ci(r.false_killer_notch, r.false_killer_notch_lo, r.false_killer_notch_hi, r.n_notch),
             _ci(r.false_killer_filament, r.false_killer_filament_lo, r.false_killer_filament_hi, r.n_filament),
             _ci(r.suppression_nuisance, r.suppression_nuisance_lo, r.suppression_nuisance_hi, r.n_nuisance)] for r in sm.itertuples()]
    parts.append("#### 1b. Sampling sweep (blur, bloom and defects fixed in nm)\n\n" + _md(
        ["Sampling", "Killer F1", "Recall bridge", "Recall open", "Recall particle", "Notch called killer", "Filament called killer", "Nuisance suppression"], rows))

    rows = [[_arm(r), f"{r.oracle_global_tau:.2f}", f"{r.oracle_global_f1:.2f} (n={int(r.n)})",
             _ci(r.oracle_per_sample_f1, r.oracle_per_sample_lo, r.oracle_per_sample_hi, r.n, False)] for r in sm.itertuples()]
    parts.append("#### 1a. Oracle tau: how much F1 is in the diagrams\n\nBest single tau chosen *in-sample* on these val patches (optimistic), "
                 "and the per-sample oracle (each patch is called correctly if any tau gives exactly the wafer's Delta-beta: an upper bound "
                 "for any rule that only moves the lifetime cut-off).\n\n" + _md(["Sampling", "Best global tau (in-sample)", "F1 at it", "Per-sample oracle F1"], rows))

    o = orc[(orc.s == 1) & (orc.blur_scale == 1.0)]
    rows = [[r.kind, int(r.n), int(r.n_wrong_at_frozen_tau),
             _ci(r.recoverable_strict, r.strict_lo, r.strict_hi, r.n_wrong_at_frozen_tau) if r.n_wrong_at_frozen_tau else "-",
             _ci(r.recoverable_loose, r.loose_lo, r.loose_hi, r.n_wrong_at_frozen_tau) if r.n_wrong_at_frozen_tau else "-",
             f"{int(r.within_0p1_of_frozen)}/{int(r.n_wrong_at_frozen_tau)}" if r.n_wrong_at_frozen_tau else "-"] for r in o.itertuples()]
    tot = o[o.n_wrong_at_frozen_tau > 0]
    ns, nw = int(tot.n_recoverable_strict.sum()), int(tot.n_wrong_at_frozen_tau.sum())
    parts.append("#### 1a. Oracle tau per error type (1 nm/px)\n\nWrong at the frozen tau = killer not flagged KILLER, or a non-killer flagged KILLER "
                 "(nuisance: also NEAR_MISS is not counted here). Strict: some tau gives exactly the wafer's Delta-beta (nothing else in the patch breaks). "
                 "Loose: some tau gives the right verdict class.\n\n" + _md(
                     ["Kind", "n", "Wrong at frozen tau", "Recoverable (strict)", "Recoverable (loose)", "Correct tau within +-0.10 of frozen"], rows)
                 + f"\n\nAll error types pooled: {ns}/{nw} recoverable (strict).")

    mech, sep = pd.read_csv(ROOT / "error_mechanism.csv"), pd.read_csv(ROOT / "separability.csv")
    rows = []
    for (s, b), g in mech.groupby(["s", "blur_scale"], sort=False):
        arm = f"{s}x" + ("" if b == 1.0 else f", optics x{b:g}")
        rows += [[arm, r.kind, r.mechanism.replace("_", " "), f"{int(r.n)}/{int(r.n_kind)}"] for r in g.itertuples()]
    parts.append("#### Error mechanisms (every wrong killer flag)\n\n" + _md(["Arm", "Kind", "Mechanism", "Errors / n"], rows))
    rows = [[f"{r.s}x" + ("" if r.blur_scale == 1.0 else f", optics x{r.blur_scale:g} (supplementary)"), r.pair, int(r.n),
             int(r.min_errors_any_threshold), f"{r.auc:.3f}"] for r in sep.itertuples()]
    parts.append("#### Separability of the decisive field value (labels used: diagnostic only)\n\nFor each killer / near-miss look-alike pair, "
                 "the fewest errors ANY single threshold on the defect saddle can make, and the AUC. A local per-gap / per-neck threshold "
                 "cannot beat this floor if it only reads the saddle.\n\n" + _md(["Arm", "Pair", "n", "Min errors, any threshold", "AUC"], rows))

    rows = [[r.kind, r.size, f"[{r.lo_nm:g}, {r.hi_nm:g})", r.metric.replace("_", " "), _ci(r.mean, r.ci_lo, r.ci_hi, r.n)] for r in sz.itertuples()]
    parts.append("#### Recall vs physical size (1 nm/px, natural size variation of the val samples)\n\n" + _md(["Kind", "Size", "Bin (nm)", "Metric", "Rate"], rows))

    m = miss[(miss.s == 1) & (miss.blur_scale == 1.0)].copy()
    size_cols = [c for c in ("p_radius", "p_gap", "p_length", "p_width", "p_clearance", "p_remaining") if c in m]

    def size(r):
        return ", ".join(f"{c[2:]} {getattr(r, c):.1f}" for c in size_cols if pd.notna(getattr(r, c)))

    rows = [[r.kind, r.verdict, f"({r.true_db0}, {r.true_db1})", f"({r.db0}, {r.db1})", size(r),
             "n/a" if pd.isna(r.saddle) else f"{r.saddle:.2f}" + ("" if pd.isna(r.peak) else f" (peak {r.peak:.2f})"),
             "n/a" if pd.isna(r.margin) else f"{r.margin:+.3f}",
             "none" if pd.isna(r.tau_ok_nearest) else f"{r.tau_ok_nearest:.2f} [{r.tau_ok_min:.2f}-{r.tau_ok_max:.2f}]"] for r in m.itertuples()]
    parts.append(f"#### 1c. Miss log (1 nm/px, every wrong killer flag, n = {len(m)})\n\nSizes in nm. Field value: the saddle (merge / cut level) at the "
                 "defect in the verifier's own field; margin > 0 means the field shows the topology change at the frozen tau. Correct tau: nearest "
                 "tau with exactly the wafer's Delta-beta [range].\n\n"
                 + _md(["Kind", "Verdict", "True dBeta", "Called dBeta", "Size (nm)", "Field at defect", "Margin to tau", "Correct tau [range]"], rows))
    return "\n\n".join(parts)


if __name__ == "__main__":
    update_block(str(DOC), render(), (START, END))
    print("updated", DOC)
